#!/bin/bash
# deps.sh DL OUT  (run inside the manylinux_2_28 root): the static third-party libraries of the portable toolchains.
#   lib/*.a  = the OFFICIAL Lean 4.37.0-rc1 release's own static archives (GMP 6.3.0, libuv 1.53.0, OpenSSL 4.1.0); built by the
#              release CI in nix oldGlibc with gcc 7.3 against glibc 2.26 -> they bind only old glibc symbol versions),
#              copied from the elan tree and checked against the pinned official manifest sha256 (the caller passes them in OFF=);
#   include/ = the headers of exactly those upstream versions (gmp.h/OpenSSL headers generated by their configure, same options
#              as the release: GMP --enable-fat --disable-shared --with-pic --disable-cxx; OpenSSL no-shared no-tests);
#   lib/pkgconfig/{gmp,libuv}.pc for Lean's FindGMP/FindLibUV.
set -euo pipefail
DL=$1 OUT=$2 OFF=${OFF:?official lib dir}
rm -rf "$OUT" "$OUT.work"; mkdir -p "$OUT/include" "$OUT/lib/pkgconfig" "$OUT.work"; W=$OUT.work
export CC=gcc
cd $W; tar xf $DL/gmp/gmp-6.3.0.tar.xz; cd gmp-6.3.0
./configure --enable-fat --disable-shared --enable-static --with-pic --disable-cxx --build=x86_64-pc-linux-gnu > ../gmp.cfg.log 2>&1
cp gmp.h $OUT/include/
cd $W; tar xf $DL/libuv153/libuv-v1.53.0.tar.gz; cp -r libuv-v1.53.0/include/* $OUT/include/
cd $W; tar xf $DL/openssl41/openssl-4.1.0.tar.gz; cd openssl-4.1.0
./Configure linux-x86_64 --prefix=/opt/fvdeps no-shared no-tests > ../openssl.cfg.log 2>&1
make -s build_generated > ../openssl.gen.log 2>&1
mkdir -p $OUT/include/openssl; cp include/openssl/*.h $OUT/include/openssl/
for a in libgmp.a libuv.a libssl.a libcrypto.a; do cp $OFF/$a $OUT/lib/; done
cat > $OUT/lib/pkgconfig/gmp.pc <<PC
prefix=/opt/fvdeps
libdir=\${prefix}/lib
includedir=\${prefix}/include
Name: GNU MP
Description: GNU Multiple Precision Arithmetic Library (static archive of the official Lean 4.37.0-rc1 release)
Version: 6.3.0
Libs: -L\${libdir} -lgmp
Cflags: -I\${includedir}
PC
cat > $OUT/lib/pkgconfig/libuv.pc <<PC
prefix=/opt/fvdeps
libdir=\${prefix}/lib
includedir=\${prefix}/include
Name: libuv
Version: 1.53.0
Description: multi-platform support library with a focus on asynchronous I/O (static archive of the official Lean 4.37.0-rc1 release)
Libs: -L\${libdir} -luv
Libs.private: -lpthread -ldl -lrt
Cflags: -I\${includedir}
PC
grep -E "define (__GNU_MP_VERSION|GMP_LIMB_BITS)" $OUT/include/gmp.h; grep -E "define UV_VERSION_(MAJOR|MINOR|PATCH) " $OUT/include/uv/version.h; grep -E "define OPENSSL_VERSION_(STR|TEXT) " $OUT/include/openssl/opensslv.h
(cd $OUT && find . -type f | sort | xargs sha256sum) > $OUT.sha256
rm -rf $W
echo DEPS-OK
