#!/usr/bin/python3 -I
"""premiseoff.py PROJECT_DIR OUT.lean   (fastverify sound preset, build option premise-off; S07)

Writes the source of the untrusted-build helper module `FastverifyPremiseOff`. It contains NO declarations; it only adds
exported entries to two deny lists of Lean's library-suggestions machinery (Lean.LibrarySuggestions.Basic):
  * typePrefixDenyListExt += the anonymous name (a prefix of every name): every premise whose
    `type.getForallBody.getAppFn` is a constant is denied;
  * nameDenyListExt += the first component of every `namespace` declared in the project's sources (most frequent last
    = first in the cons-built state list): covers the remaining theorems of the project (types whose body head is a
    `let`, a bound variable, ...).
Every module that imports the helper therefore skips the premise-selection metadata that `sineQuaNonExt` and
`symbolFrequencyExt` compute in their export functions when the .olean is written (the dominant cost of many heavy
modules). The deny lists are read only by library-suggestion selectors (MePo, SineQuaNon, `exact?`-style suggestion
engines), never by the kernel, the elaborator's core or the exporter; the build is untrusted anyway (the export is
re-checked by the trusted kernels against the official challenge), so this can only cause a failed build, never an accept.
Project sources are read as text only (never executed)."""
import collections, os, re, sys
from concurrent.futures import ThreadPoolExecutor

NS = re.compile(rb'^[ \t]*namespace[ \t]+([^\s.]+)', re.M)
ROOT = None   # realpath of PROJ; only regular files that ARE inside it are read (host-side helper)


def project_files(root):
    """.lean files below the REAL project root (no '.lake' / hidden dirs), without following a directory symlink: regular
    files as listed, a file symlink only if it resolves to a regular file inside the project (its target is read), never a
    FIFO / device / socket. Runs while Lake plans: no untrusted code runs concurrently (the build has not started)."""
    out, stack = [], [root]
    while stack:
        d = stack.pop()
        try:
            it = list(os.scandir(d))
        except OSError:
            continue
        for e in it:
            if e.is_dir(follow_symlinks=False):
                if e.name != '.lake' and not e.name.startswith('.'):
                    stack.append(e.path)
            elif e.name.endswith('.lean'):
                if e.is_file(follow_symlinks=False):
                    out.append(e.path)
                elif e.is_symlink():
                    t = os.path.realpath(e.path)
                    if t.startswith(ROOT + os.sep) and os.path.isfile(t):
                        out.append(t)
    return out


def scan(paths):
    c = collections.Counter()
    for p in paths:
        try:
            with open(p, 'rb') as f: data = f.read()
        except OSError:
            continue
        for m in NS.finditer(data):
            c[m.group(1)] += 1
    return c


def main(a):
    if len(a) != 2:
        print(__doc__); return 2
    proj, out = a
    global ROOT
    ROOT = os.path.realpath(proj)
    files = project_files(ROOT)
    chunks = [files[i::32] for i in range(32)]
    tot = collections.Counter()
    with ThreadPoolExecutor(32) as ex:
        for c in ex.map(scan, chunks): tot.update(c)
    roots = []
    for b, n in tot.items():
        try: s = b.decode('utf-8')
        except UnicodeDecodeError: continue
        # plain identifiers only (no escapes / quotes / spaces); anything else is simply not denied by name
        if s and all(ch.isalnum() or ch in "_'!?" or ord(ch) > 127 for ch in s) and not s[0].isdigit():
            roots.append((n, s))
    roots.sort()   # ascending frequency: addEntry conses, so the most frequent root ends up first in the state list
    words = ' '.join(s for _, s in roots)
    src = ('import Lean.LibrarySuggestions.Basic\n'
           '/-! fastverify sound preset, build option premise-off (untrusted build helper, generated by build/premiseoff/premiseoff.py).\n'
           'No declarations: exported deny-list entries only, so importers skip the premise-selection metadata at .olean write. -/\n'
           'run_cmd Lean.modifyEnv fun env => Lean.LibrarySuggestions.typePrefixDenyListExt.addEntry env Lean.Name.anonymous\n')
    if words:
        src += ('run_cmd Lean.modifyEnv fun env => ("' + words + '".splitOn " ").foldl (init := env) fun env s =>\n'
                '  Lean.LibrarySuggestions.nameDenyListExt.addEntry env s\n')
    with open(out, 'w', encoding='utf-8') as f: f.write(src)
    print(f'premiseoff: {len(files)} sources, {len(roots)} namespace roots denied by name')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
