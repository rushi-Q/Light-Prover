#!/usr/bin/env python3
"""attrhide.py SRC OUT --mode check|hide|hide-all|hide-auto [--matched RESULTS_DIR] [--stats FILE]

ERASURE-LIST FACTORING for the AI-FLT layout. Every card / proof file of the AI FLT pins its
elaboration context with long explicit lists `attribute [-instance] a b ...` / `attribute [-simp] a b ...` (362 MB,
32 % of the source). Hypothesis: each list is generated by ONE rule - erase every project (Definitions/P2M/Theorems)
simp lemma / instance that is visible but not visible from the file's own non-alias imports (imports that are not
Theorems.* cards or P2M.Sol.* proofs). P2MHide.lean.in (appended to P2M/Util.lean) implements the rule.

--mode check : every file whose erase lines form ONE contiguous block gets, instead of the block,
               `p2m_hide_check inst (VIS) <the instance names>` + `p2m_hide_check simp (VIS) <the simp names>`
               (erases exactly the original names, and records L vs the rule set R in .lake/p2m_hide/<module>.<kind>).
--mode hide  : files whose recorded check had L = R for every kind present (RESULTS_DIR = the .lake/p2m_hide dir of a
               check build) get `p2m_hide inst (VIS)` / `p2m_hide simp (VIS)` instead of the block; others stay unchanged.
--mode hide-all : (G2) every contiguous block becomes `p2m_hide` lines, without a check (where the generated set differs
               from the explicit one, elaboration may change: measured by the build + trusted check).
--mode hide-auto : files with a recorded check: as `hide`; files without one (check build incomplete): as `hide-all`.
VIS = the file's non-alias imports. Text only; the result is judged by the build + the trusted check (any difference in
the erased sets can only change elaboration, i.e. make the build fail or produce other declarations).
"""
import json, os, re, shutil, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ERASE_RE = re.compile(r'^attribute \[-(instance|simp)\] (.*)$')


def modname(root, path):
    return os.path.relpath(path, root)[:-5].replace(os.sep, '.')


def imports_of(lines):
    imps = []
    for l in lines:
        if l.startswith('import '): imps.append(l.split()[1])
        elif l.strip() == '' or l.startswith('--'): continue
        else: break
    return imps


SKIP_RE = re.compile(r'(^|\.)_sizeOf_inst$|^P2MW\..*\.(injEq|sizeOf_spec)$')   # = generatorSkips in P2MHide.lean.in


def load_results(d):
    """module -> kind -> True iff the explicit list L equals the refined rule set (R minus generatorSkips)"""
    ok = {}
    if not d: return ok
    nm = lambda s: [x.strip() for x in s.strip()[1:-1].split(',') if x.strip()]
    for f in os.listdir(d):
        mod, kind = f.rsplit('.', 1)
        l = open(os.path.join(d, f)).read().split('\n')
        lmr = nm(l[1][4:]) if len(l) > 1 and l[1].startswith('LmR ') else ['?']
        rml = nm(l[2][4:]) if len(l) > 2 and l[2].startswith('RmL ') else ['?']
        ok.setdefault(mod, {})[kind] = (not lmr and all(SKIP_RE.search(n) for n in rml))
    return ok


def main():
    a = sys.argv[1:]
    src, out = os.path.abspath(a[0]), os.path.abspath(a[1])
    opt = lambda k, d=None: a[a.index(k) + 1] if k in a else d
    mode = opt('--mode', 'check'); res = load_results(opt('--matched')); stats_path = opt('--stats')
    if mode in ('hide', 'hide-auto') and not res: print(f'--mode {mode} needs --matched RESULTS_DIR'); sys.exit(2)
    if os.path.exists(out): print(f'refusing: {out} exists'); sys.exit(2)
    shutil.copytree(src, out, ignore=shutil.ignore_patterns('.lake', '.git'))
    util = os.path.join(out, 'P2M', 'Util.lean')
    with open(util, 'a', encoding='utf-8') as f: f.write(open(os.path.join(HERE, 'P2MHide.lean.in'), encoding='utf-8').read())
    st = collections.Counter()
    for d, dirs, fs in os.walk(out):
        dirs[:] = [x for x in dirs if x not in ('.lake', '.git')]
        for fn in fs:
            if not fn.endswith('.lean'): continue
            p = os.path.join(d, fn); m = modname(out, p)
            if not (m.startswith('Theorems.') or m.startswith('P2M.Sol.')): continue
            text = open(p, encoding='utf-8').read(); lines = text.split('\n')
            idx = [i for i, l in enumerate(lines) if ERASE_RE.match(l)]
            if not idx: st['no_lists'] += 1; continue
            if idx != list(range(idx[0], idx[-1] + 1)): st['not_contiguous'] += 1; continue
            names = collections.defaultdict(list)
            for i in idx:
                k, rest = ERASE_RE.match(lines[i]).groups()
                names['inst' if k == 'instance' else 'simp'].extend(rest.split())
            vis = [x for x in imports_of(lines) if not (x.startswith('Theorems.') or x.startswith('P2M.Sol.'))]
            if mode == 'check':
                new = [f'p2m_hide_check {k} ({" ".join(vis)}) {" ".join(v)}' for k, v in names.items()]
            elif mode == 'hide-all':
                new = [f'p2m_hide {k} ({" ".join(vis)})' for k in names]
            elif mode == 'hide-auto' and m not in res:
                st['hidden_unchecked'] += 1
                new = [f'p2m_hide {k} ({" ".join(vis)})' for k in names]
            else:
                r = res.get(m, {})
                kinds = {'inst': 'instance', 'simp': 'simp'}
                if not all(r.get(kinds[k]) for k in names): st['kept_explicit'] += 1; continue
                new = [f'p2m_hide {k} ({" ".join(vis)})' for k in names]
            before = sum(len(lines[i]) + 1 for i in idx); after = sum(len(x) + 1 for x in new)
            lines[idx[0]:idx[-1] + 1] = new
            with open(p, 'w', encoding='utf-8') as fh: fh.write('\n'.join(lines))
            st['rewritten'] += 1; st['bytes_before'] += before; st['bytes_after'] += after
    r = {'mode': mode, **st}
    print(json.dumps(r, indent=1))
    if stats_path: json.dump(r, open(stats_path, 'w'), indent=1)


if __name__ == '__main__':
    main()
