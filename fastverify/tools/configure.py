#!/usr/bin/python3 -I
"""tools/configure.py [--elan-home DIR] [--light-lean DIR] [--check-only]

Writes config/components.json for THIS machine from config/components.template.json (the published, machine-independent
form): ${ELAN_HOME} = the elan home with the official toolchains (default: <home of the invoking user>/.elan),
${LIGHT_LEAN} = the directory holding env/tools/lean4export (default: the package's parent), ${FASTVERIFY} = the package.
Then verifies every pinned file (official toolchain binaries, official exporter) against its sha256; exit 0 iff all match.
The package never reads paths from the environment; run this once per installation (bin/fastverify --preflight-only then
verifies the whole toolchain trees and every stage)."""
import argparse, hashlib, json, os, pwd, sys

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 22), b""):
            h.update(b)
    return h.hexdigest()


def expand(o, v):
    if isinstance(o, str):
        for k, x in v.items():
            o = o.replace("${" + k + "}", x)
        return o
    if isinstance(o, list):
        return [expand(x, v) for x in o]
    if isinstance(o, dict):
        return {k: expand(x, v) for k, x in o.items()}
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--elan-home", default=os.path.join(pwd.getpwuid(os.getuid()).pw_dir, ".elan"))
    ap.add_argument("--light-lean", default=os.path.dirname(ROOT))
    ap.add_argument("--check-only", action="store_true", help="only verify the current config/components.json")
    a = ap.parse_args()
    out = os.path.join(ROOT, "config", "components.json")
    if a.check_only:
        c = json.load(open(out))
    else:
        t = json.load(open(os.path.join(ROOT, "config", "components.template.json")))
        c = expand(t, {"ELAN_HOME": os.path.realpath(a.elan_home), "LIGHT_LEAN": os.path.realpath(a.light_lean),
                       "FASTVERIFY": ROOT})
        c["comment"] = "GENERATED by tools/configure.py from components.template.json - " + c.get("comment", "")
        if sys.platform == "darwin":   # the macOS pins of an entry replace its Linux ones; an entry without is left out
            # (an exporter without a macOS pin keeps its Linux digest: the check below reports the mismatch)
            m = json.load(open(os.path.join(ROOT, "config", "components.macos.json")))
            c["lean_toolchains"] = {tid: t for tid, t in c["lean_toolchains"].items() if tid in m["lean_toolchains"]}
            for tid, t in c["lean_toolchains"].items():
                o = m["lean_toolchains"][tid]
                t.update(lean_version=o["lean_version"], sha256=o["sha256"])
                t["official_lean4export"].update(o.get("official_lean4export", {}))
            del c["comparator"]   # programs of the Linux judge
    bad = 0
    pins = []
    for tid, t in c["lean_toolchains"].items():
        pins += [(os.path.join(t["prefix"], k), v) for k, v in t["sha256"].items()]
        pins.append((t["official_lean4export"]["path"], t["official_lean4export"]["sha256"]))
    if sys.platform != "darwin" or "comparator" in c:   # (left out on macOS only: elsewhere a missing entry is an error)
        pins += [(os.path.join(c["comparator"]["prefix"], k), v) for k, v in c["comparator"]["sha256"].items()]
    for p, want in pins:
        try:
            have = sha256(p)
        except OSError as e:
            print(f"MISSING {p}: {e.strerror}"); bad += 1; continue
        print(("OK      " if have == want else "MISMATCH") + f" {p}")
        bad += have != want
    if not a.check_only:
        if "${" in json.dumps(c):
            print("unexpanded variable left in the configuration"); return 2
        tmp = out + ".new"
        with open(tmp, "w") as f:
            json.dump(c, f, indent=2); f.write("\n")
        os.replace(tmp, out)
        print(f"wrote {out}")
    print("configure: " + ("all pinned files present and matching" if not bad else f"{bad} problem(s)"))
    return 0 if not bad else 2


if __name__ == "__main__":
    sys.exit(main())
