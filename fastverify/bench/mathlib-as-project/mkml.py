#!/usr/bin/env python3
"""mkml.py SRC_MATHLIB OUTROOT : generate the "Mathlib as the project" benchmark cases.
For every case: OUTROOT/proj/<case>/ = Mathlib 0df444a sources (hard links; no .lake/.git/lakefile.lean) + lakefile.toml
(Mathlib's lakefile.lean options, translated) + Solution.lean; OUTROOT/chal/<case>/ = clean challenge (imports the
TRUSTED cached Mathlib; statements `type_of% @Name` or explicit), comparator.json, lakefile.toml, manifest, toolchain."""
import json, os, shutil, subprocess, sys
SRC, OUT = sys.argv[1], sys.argv[2]
WS_MANIFEST = os.environ.get("WS_MANIFEST", "$LIGHT_LEAN/verify/challenge/lake-manifest.json")
AX = ["propext", "Quot.sound", "Classical.choice"]
# case -> (imports of the solution, [(theorem name, statement source, proof term)], default targets incl. Mathlib?)
T = lambda n, c: (n, f"type_of% @{c}", f"@{c}")
CASES = {
  "prime":     (["Mathlib.Data.Nat.Prime.Infinite"], [T("ml_two_le", "Nat.Prime.two_le"), T("ml_inf_primes", "Nat.exists_infinite_primes")], False),
  "sylow":     (["Mathlib.GroupTheory.Sylow"], [T("ml_sylow1", "Sylow.exists_subgroup_card_pow_prime"), T("ml_sylow3", "card_sylow_modEq_one")], False),
  "qr":        (["Mathlib.NumberTheory.LegendreSymbol.QuadraticReciprocity"], [T("ml_qr", "legendreSym.quadratic_reciprocity")], False),
  "dirichlet": (["Mathlib.NumberTheory.LSeries.PrimesInAP"], [T("ml_dirichlet", "Nat.forall_exists_prime_gt_and_eq_mod")], False),
  "isd":       (["Mathlib.Order.Interval.Set.Defs"], [T("ml_ioo_def", "Set.Ioo_def")], False),
  "withbot":   (["Mathlib.Order.WithBot"], [T("ml_withbot_coe_le", "WithBot.coe_le_coe")], False),
  # dualmut: the target is a declaration GENERATED by @[to_dual] (Mathlib/Order/Defs/PartialOrder.lean l.215); with
  # skip-kernel-tc the generator keeps an ill-typed first attempt -> natural kernel-invalid mutant
  "dualmut":   (["Mathlib.Order.Defs.PartialOrder"], [T("ml_dual", "Decidable.lt_or_eq_of_le'")], False),
  "whole":     (["Mathlib"], [T("ml_two_le", "Nat.Prime.two_le"), T("ml_inf_primes", "Nat.exists_infinite_primes"),
                              T("ml_sylow1", "Sylow.exists_subgroup_card_pow_prime"), T("ml_sylow3", "card_sylow_modEq_one"),
                              T("ml_qr", "legendreSym.quadratic_reciprocity"), T("ml_dirichlet", "Nat.forall_exists_prime_gt_and_eq_mod"),
                              T("ml_basel", "hasSum_zeta_two"), T("ml_fta", "Complex.exists_root"),
                              T("ml_hilbert", "Polynomial.isNoetherianRing"), T("ml_liouville", "Liouville.transcendental")], True),
}
LEANOPTS = """leanOptions = { pp.unicode.fun = true, autoImplicit = false, maxSynthPendingDepth = 3, weak.linter.mathlibStandardSet = true, weak.linter.style.header = true, weak.linter.checkInitImports = true, weak.linter.allScriptsDocumented = true, weak.linter.pythonStyle = true, weak.linter.style.longFile = 1500 }"""
REQ = ""
man = {p["name"]: p for p in json.load(open(os.path.join(SRC, "lake-manifest.json")))["packages"]}
for n in ["batteries", "Qq", "aesop", "proofwidgets", "importGraph", "LeanSearchClient", "plausible"]:  # lakefile.lean order
    p = man[n]
    REQ += f'\n[[require]]\nname = "{p["name"]}"\nscope = "{p["scope"]}"\nrev = "{p["inputRev"]}"\n'
os.makedirs(os.path.join(OUT, "proj"), exist_ok=True); os.makedirs(os.path.join(OUT, "chal"), exist_ok=True)
ONLY = os.environ.get('ONLY', '').split(',') if os.environ.get('ONLY') else None
for case, (imps, thms, whole) in CASES.items():
    if ONLY and case not in ONLY: continue
    pd = os.path.join(OUT, "proj", case)
    if os.path.exists(pd): shutil.rmtree(pd)
    subprocess.run(["cp", "-al", SRC, pd], check=True)
    for x in ("lakefile.lean",):
        if os.path.exists(os.path.join(pd, x)): os.unlink(os.path.join(pd, x))
    dt = '["Mathlib", "Solution"]' if whole else '["Solution"]'
    with open(os.path.join(pd, "lakefile.toml"), "w") as f:
        f.write(f'name = "mathlib"\ndefaultTargets = {dt}\n{REQ}\n[[lean_lib]]\nname = "Mathlib"\n{LEANOPTS}\n\n'
                f'[[lean_lib]]\nname = "Solution"\n{LEANOPTS}\n')
    with open(os.path.join(pd, "Solution.lean"), "w") as f:
        f.write("".join(f"import {m}\n" for m in imps) + f"\n/-! Mathlib-as-project case `{case}` -/\n\n")
        for n, st, pf in thms: f.write(f"theorem {n} : {st} :=\n  {pf}\n\n")
    cd = os.path.join(OUT, "chal", case)
    if os.path.exists(cd): shutil.rmtree(cd)
    os.makedirs(cd)
    with open(os.path.join(cd, "Challenge.lean"), "w") as f:
        f.write(f"import Mathlib\n\n/-! Clean challenge for case `{case}` (statements against the trusted cached Mathlib) -/\n\n")
        for n, st, pf in thms: f.write(f"theorem {n} : {st} :=\n  sorry\n\n")
    json.dump({"challenge_module": "Challenge", "solution_module": "Solution", "theorem_names": [n for n, _, _ in thms],
               "definition_names": [], "permitted_axioms": AX}, open(os.path.join(cd, "comparator.json"), "w"), indent=1)
    with open(os.path.join(cd, "lakefile.toml"), "w") as f:
        f.write(f'name = "mlchal_{case}"\ndefaultTargets = ["Challenge"]\n\n[[require]]\nname = "mathlib"\n'
                f'git = "https://github.com/leanprover-community/mathlib4"\nrev = "0df444a360eaa60ab8c11dca51a86af692955474"\n\n'
                f'[[lean_lib]]\nname = "Challenge"\n')
    wm = json.load(open(WS_MANIFEST)); wm["name"] = f"mlchal_{case}"
    json.dump(wm, open(os.path.join(cd, "lake-manifest.json"), "w"), indent=1)
    shutil.copy(os.path.join(SRC, "lean-toolchain"), cd)
    print(case, pd, cd)
