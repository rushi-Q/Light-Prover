#!/usr/bin/env python3
"""mkprefix.py PROJECT FILE THEOREM [OUT] : generate the challenge copy of a project file (same path, same module name) = the file's text up to the
declaration of THEOREM (imports, options, namespaces, every earlier definition and lemma, verbatim) + THEOREM's statement
with ':= sorry'. The statement is then elaborated in exactly its original context (same imports, opens, variables,
instances, earlier local definitions), which is what compareAt needs; earlier lemmas keep their proofs (only statements
of the targets matter). Lean 4 needs no closing `end` at EOF. Used by tools/fetch.sh for challenges/<name>/prefix.txt."""
import re, sys
proj, rel = sys.argv[1:3]; names = sys.argv[3].split(',')
src = open(f'{proj}/{rel}', encoding='utf-8').read()
# several targets (comma-separated): cut at the one that comes LAST in the file; the earlier ones stay as they are
# (with their proofs: compareAt compares only the statements of target theorems)
def find(name):
    return re.search(r'(?m)^[ \t]*(?:@\[[^\n]*\]\s*\n[ \t]*)?(?:(?:private|protected|nonrec)\s+)?(theorem|lemma) ' + re.escape(name) + r'(?=[\s({\[:])', src)
ms = [(find(n), n) for n in names]
for mm, n in ms:
    if not mm: sys.exit(f'mkprefix: theorem {n} not found in {rel}')
m, name = max(ms, key=lambda t: t[0].start())
start = m.start()
# statement end: first ':=' at bracket depth 0 that is not inside a `let ... :=` of the statement, or ' where'/'|' (eqns)
i, depth, lets = m.end(), 0, 0
while i < len(src):
    c = src[i]
    if c in '([{⟨': depth += 1
    elif c in ')]}⟩': depth -= 1
    elif depth == 0 and re.match(r'\blet\b|\bhave\b', src[i:i + 5]) and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == '_')):
        lets += 1
    elif src.startswith(':=', i) and depth == 0:
        if lets: lets -= 1
        else: break
    i += 1
stmt = src[start:i].rstrip()
out = (f'/- GENERATED by bench/codeprojects/tools/mkprefix.py from {rel} (pinned commit, see projects.tsv): the file up to\n'
       f'   `{name}` verbatim + its statement with `sorry`. -/\n' + src[:start] + stmt + ' := sorry\n')
open(sys.argv[4] if len(sys.argv) > 4 else '/dev/stdout', 'w', encoding='utf-8').write(out)
