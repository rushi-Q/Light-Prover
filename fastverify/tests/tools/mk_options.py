#!/usr/bin/env python3
"""mk_options.py [OUT] : write the per-option test matrix (one entry point, a menu of options
per stage, tests per option). Reads the latest tests/results/<stamp>-opt-<option>.tsv/.json of each option
run (tools/option_matrix.sh) and, for the default configuration, the latest *full* run. OUT defaults to
$FV_TEST_WORK/OPTIONS.md (a generated file: the repository does not keep one)."""
import collections, glob, json, os, sys

T = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
R = os.path.join(T, 'results')
latest = {}
for p in sorted(glob.glob(os.path.join(R, '*.tsv')), key=os.path.getmtime):
    b = os.path.basename(p)[:-4]
    stamp, _, label = b.partition('-')
    if label.startswith('opt-') or 'full' in label:
        key = label if label.startswith('opt-') else 'default (full run: ' + label + ')'
        if 'full' in label:
            key = 'default'
        latest[key] = (p, stamp, label)
EXPECT = {
    # before check A was retired: default = B1+E1, C1,C3,C0 (--check both); opt-fastexact; b2/e0 with C1
    'default': 'B1+E1, checks C3,C0 (--check C3,C0)', 'opt-reference': 'B0+E0+C0 (--preset reference)',
    'opt-fastexact': 'B2+E1+C1 (--preset fast-exact, retired)', 'opt-b2': 'B2+E1, C3,C0', 'opt-e0': 'B1+E0, C3,C0',
    'opt-c3': 'B1+E1, C3 only', 'opt-c4': 'B1+E1, C4 only (UNSAFE)', 'opt-c4io': 'B1+E1, C4 + ignore-order (UNSAFE)',
    'opt-c2': 'B1+E1, C2 only (UNSAFE; retired)'}
rows = []
order = ['default', 'opt-reference', 'opt-fastexact', 'opt-b2', 'opt-e0', 'opt-c3', 'opt-c2', 'opt-c4', 'opt-c4io']
keys = [k for k in order if k in latest] + sorted(k for k in latest if k not in order)
for k in keys:
    p, stamp, label = latest[k]
    meta = {}
    try:
        meta = json.load(open(p[:-4] + '.json'))
    except Exception:
        pass
    cnt = collections.Counter(); bad = collections.defaultdict(set)
    for ln in open(p):
        f = ln.rstrip('\n').split('\t')
        if len(f) < 7 or f[0] == 'id':
            continue
        cnt[f[6]] += 1
        if f[6].startswith(('FAIL', 'UNSAFE-FAIL', 'ERROR')):
            bad[f[6]].add(f[0])
    summ = ', '.join(f'{v} {c}' for c, v in sorted(cnt.items()))
    fails = '; '.join(f"{c}: {' '.join(sorted(ids))}" for c, ids in sorted(bad.items())) or '-'
    what = EXPECT.get(k, meta.get('fv_args', ''))
    if k.startswith('opt-unsafe-'):
        what = 'B3 ' + k[len('opt-unsafe-'):] + ' (UNSAFE opt-in)'
    rows.append((k.replace('opt-', ''), what, meta.get('fv_args', '--check C3,C0'), stamp, summ, fails))
OUT = sys.argv[1] if len(sys.argv) > 1 else (os.path.join(os.environ['FV_TEST_WORK'], 'OPTIONS.md') if os.environ.get('FV_TEST_WORK') else None)
if not OUT:
    sys.exit('mk_options.py: give OUT or set FV_TEST_WORK')
with open(OUT, 'w') as o:
    o.write('# Regression tests per menu option (generated by tests/tools/mk_options.py from tests/results/)\n\n'
            'Each row = one run of the regression tests with the package options shown (`run_all.sh --fv-args ...`, driven by '
            '`tools/option_matrix.sh`). Exact options (default, reference, fast-exact, B2, E0, C3) must have no FAIL row. '
            'UNSAFE opt-ins (B3 options, C2, C4, ignore-order) are run on the findings they are documented to break: their '
            'FAIL rows are reported as UNSAFE-FAIL-* and are the expected, documented breakage (the README option matrix lists the '
            'finding ids). Export-level tests run every check option (C1, C2!unsafe, C3, C4!unsafe) in every suite run.\n\n')
    o.write('| option | configuration | --fv-args | run | rows | failing tests |\n|---|---|---|---|---|---|\n')
    for r in rows:
        o.write('| ' + ' | '.join(str(x).replace('|', '/') for x in r) + ' |\n')
print(f'{OUT}: {len(rows)} option runs')
