#!/bin/bash
# tests/sound-auto/run.sh [SCRATCH] : regression test of --preset sound-auto:
#   unit   lib/autotune.py rows (header parser, default-target closure, decisions on synthetic projects / mocked hosts)
#   sched  build/sched.py --ktc-exempt-translate without its --extra-arg -> DECLINE (exit 3)
#   e2e    core-only cases of g11 through bin/fastverify --preset sound-auto (16 threads):
#            ok     honest one-module proof          -> ACCEPTED, build B0 (one module: the official lake build)
#            stmt   proof of a different statement   -> REJECTED
#            kfalse 'decide +kernel' on 2+2=5         -> REJECTED, build B3 (kernel-heavy marker; skip-kernel-tc build
#                                                        passes, the trusted kernels reject)
#          ok2/ok3 integrity records reused on a 2nd run (svc check, tree records); --no-integrity-cache -> full
#          frontier (the frontier test's 'decomp' case, when check/frontier preflights): sound-auto + --modulo-frontier auto -> exit 3
#            CONDITIONAL with 2 open lemmas
#          dualmut (needs the trusted workspace's Mathlib sources, ~2-4 min): the Mathlib-as-project slice of confirm-reject
#            (target generated by @[to_dual]) -> ACCEPTED with skip-kernel-tc=except-translate (>= 1 'ktc-exempt' module)
#            where --preset sound falsely REJECTS (tests/confirm-reject documents that).
# Prints PASS/FAIL rows and RESULT; exit 0 iff all PASS.
set -u
H=$(cd "$(dirname "$(readlink -f "$0")")" && pwd); PKG=$(cd "$H/../.." && pwd); FV=$PKG/bin/fastverify
LL=$(cd "$PKG/.." && pwd); WS=${WS:-$LL/verify/challenge}; G11=$PKG/tests/confirm-reject
S=$(mktemp -d "${1:-${TMPDIR:-/tmp}}/sound-auto.XXXXXX") || exit 2
trap 'chmod -R u+w "$S" 2>/dev/null; rm -rf "$S"' EXIT
pass=0; fail=0
ok() { echo "PASS $*"; pass=$((pass+1)); }
ko() { echo "FAIL $*"; fail=$((fail+1)); }
# --- unit
while read -r st rest; do case $st in PASS) ok "unit $rest";; FAIL) ko "unit $rest";; esac; done < <(python3 -I "$H/unit.py" "$PKG" 2>&1)
# --- sched option guard
out=$(python3 -I "$PKG/build/sched.py" 4 --ktc-exempt-translate < /dev/null 2>&1); rc=$?
if [ $rc = 3 ] && printf '%s' "$out" | grep -q 'DECLINE: --ktc-exempt-translate needs'; then ok "sched --ktc-exempt-translate alone declines"; else ko "sched guard: rc=$rc $out"; fi
# --- e2e
row() { # case want_verdict want_build
  local v; v=$(python3 -I -c 'import json,sys; r=json.load(open(sys.argv[1])); print(r.get("verdict"), r.get("exit"), (r.get("build") or {}).get("option"), "auto" if r.get("autotune") else "noauto")' "$S/$1/result.json" 2>/dev/null)
  if [ "$v" = "$2 $3 auto" ]; then ok "e2e $1: $v"; else ko "e2e $1: got '$v' want '$2 $3 auto'"; fi
}
run() { # case proj chal
  env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" "$2" "$3" "$S/$1" --preset sound-auto --threads 16 --packages "$WS" \
    > "$S/$1.log" 2>&1
}
for c in ok stmt kfalse; do run $c "$G11/proj/$c" "$G11/chal/$c"; done
# (the 'ok' run keeps its export for the export-in row below: --keep-work is not needed, solution.export stays in OUT)
row ok "ACCEPTED 0" B0; row stmt "REJECTED 1" B0; row kfalse "REJECTED 1" B3
# integrity records: a second 'ok' run reuses the records written by the first (tree stamps + check-sound-svc.sh
# --integrity-cache) with the same verdict; --no-integrity-cache verifies everything in full with the plain check-sound.sh
run ok2 "$G11/proj/ok" "$G11/chal/ok"
env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" "$G11/proj/ok" "$G11/chal/ok" "$S/ok3" --preset sound-auto --threads 16 \
  --packages "$WS" --no-integrity-cache > "$S/ok3.log" 2>&1
v=$(python3 -I - "$S/ok2/result.json" "$S/ok3/result.json" <<'PY' 2>&1
import json, sys
out = []
for f in sys.argv[1:]:
    r = json.load(open(f)); c = r.get("components", {})
    trees = [v.get("integrity") or "full" for k, v in sorted(c.items()) if k.startswith("toolchain-tree:")]
    rec = all(t.startswith("record") for t in trees) and bool(trees)
    cs = (c.get("stage:CS") or {}).get("path", "").rsplit("/", 1)[-1]
    out.append(f"{r.get('verdict')}:{'records' if rec else 'full'}:{cs}")
print(" ".join(out))
PY
)
if [ "$v" = "ACCEPTED:records:check-sound-svc.sh ACCEPTED:full:check-sound.sh" ]; then ok "e2e integrity records: reused on the 2nd run; --no-integrity-cache -> full: $v"
else ko "e2e integrity records: got '$v'"; fi
# memory budgets (needs a cgrun scope launcher: cgroup v2 scopes): under 8 GB the low-memory exporter goes first and gives the
# same export; under 1.6 GB an export-in check runs the low-memory trusted check instead of check-sound.sh
CGRUN=${FV_CGRUN:-}; [ -n "$CGRUN" ] || [ ! -x /usr/local/bin/cgrun ] || CGRUN=/usr/local/bin/cgrun; [ -n "$CGRUN" ] || CGRUN=$(command -v cgrun 2>/dev/null || true)   # FV_CGRUN, else /usr/local/bin/cgrun, else cgrun on PATH
CG=""; [ -n "$CGRUN" ] && [ -x "$CGRUN" ] && CG=$CGRUN
if [ -n "$CG" ] && [ -f "$S/ok/result.json" ] && [ -x "$PKG/export/export-lowmem.sh" ]; then
  "$CG" --mem 8G --name sound-auto-t1 -- env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" "$G11/proj/ok" "$G11/chal/ok" "$S/ok-8g" \
    --preset sound-auto --threads 8 --packages "$WS" > "$S/ok-8g.log" 2>&1
  v=$(python3 -I -c 'import json,sys; a=json.load(open(sys.argv[1])); b=json.load(open(sys.argv[2])); print(a.get("verdict"), (a.get("export") or {}).get("option"), (a.get("export") or {}).get("sha256") == (b.get("export") or {}).get("sha256"))' "$S/ok-8g/result.json" "$S/ok/result.json" 2>/dev/null)
  if [ "$v" = "ACCEPTED E1-lowmem True" ]; then ok "e2e 8 GB budget: low-memory exporter first, same export, ACCEPTED"; else ko "e2e 8 GB budget: got '$v'"; fi
  X=$(python3 -I -c 'import json,sys; print((json.load(open(sys.argv[1])).get("export") or {}).get("path",""))' "$S/ok/result.json" 2>/dev/null)
  if [ -n "$X" ] && [ -f "$X" ] && [ -f "$PKG/check/lowmem/check-sound-lowmem.sh" ]; then
    "$CG" --mem 1600M --name sound-auto-t2 -- env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" - "$G11/chal/ok" "$S/exin-1600m" \
      --preset sound-auto --from-export "$X" --threads 8 > "$S/exin-1600m.log" 2>&1
    v=$(python3 -I -c 'import json,sys; r=json.load(open(sys.argv[1])); print(r.get("verdict"), ((r.get("autotune") or {}).get("check_plan") or {}).get("lowmem"))' "$S/exin-1600m/result.json" 2>/dev/null)
    if [ "$v" = "ACCEPTED True" ]; then ok "e2e export-in under 1.6 GB, no project: low-memory trusted check, ACCEPTED"; else ko "e2e export-in 1.6 GB: got '$v'"; fi
  fi
else
  echo "SKIP memory-budget rows: no cgroup tool (FV_CGRUN, /usr/local/bin/cgrun or cgrun on PATH), or the low-memory exporter/check is not installed"
fi
# The trusted check's pins. A 4.37.0-rc1 project (g11 'ok' with its lean-toolchain switched) under sound-auto is judged by
# check/sound/pins-437.env (the check built from 4.37.0-rc1) when this package lists that release; a --pins outside
# check/sound/ is refused
if [ -f "$PKG/check/sound/pins-437.env" ] && grep -q '"leanprover/lean4:v4.37.0-rc1"' "$PKG/config/components.json" 2>/dev/null; then
  mkdir -p "$S/r437"; cp -r "$G11/proj/ok" "$S/r437/proj"; cp -r "$G11/chal/ok" "$S/r437/chal"
  echo "leanprover/lean4:v4.37.0-rc1" > "$S/r437/proj/lean-toolchain"; echo "leanprover/lean4:v4.37.0-rc1" > "$S/r437/chal/lean-toolchain"
  env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" "$S/r437/proj" "$S/r437/chal" "$S/r437/out" --preset sound-auto \
    --threads 16 > "$S/r437.log" 2>&1
  v=$(python3 -I -c 'import json,sys; r=json.load(open(sys.argv[1])); print(r.get("verdict"), (r.get("check_pins") or {}).get("path","default").split("/")[-1], r["checks"]["sound"]["stage"].get("toolchain"))' "$S/r437/out/result.json" 2>/dev/null)
  if [ "$v" = "ACCEPTED pins-437.env leanprover/lean4:v4.37.0-rc1" ]; then ok "e2e 4.37 project: sound-auto picks the 4.37 judge: $v"; else ko "e2e 4.37 project: got '$v'"; fi
  # ... and under 1.6 GB the same 4.37 export (export-in) goes to the low-memory check with its sibling pins file
  # check/lowmem/pins-437.env and the release's hide list
  X7=$(python3 -I -c 'import json,sys; print((json.load(open(sys.argv[1])).get("export") or {}).get("path",""))' "$S/r437/out/result.json" 2>/dev/null)
  if [ -n "$CG" ] && [ -n "$X7" ] && [ -f "$X7" ] && [ -f "$PKG/check/lowmem/pins-437.env" ]; then
    "$CG" --mem 1600M --name sound-auto-t3 -- env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" - "$S/r437/chal" "$S/r437-1600m" \
      --preset sound-auto --from-export "$X7" --threads 8 > "$S/r437-1600m.log" 2>&1
    v=$(python3 -I -c 'import json,sys; r=json.load(open(sys.argv[1])); c=r.get("components") or {}
print(r.get("verdict"), ((r.get("autotune") or {}).get("check_plan") or {}).get("lowmem"), "/".join((c.get("check_pins_lowmem") or {}).get("path","none").split("/")[-3:]), bool(c.get("check_hide")))' "$S/r437-1600m/result.json" 2>/dev/null)
    if [ "$v" = "ACCEPTED True check/lowmem/pins-437.env True" ]; then ok "e2e 4.37 export-in under 1.6 GB: low-memory check with check/lowmem/pins-437.env + hide list, ACCEPTED"
    else ko "e2e 4.37 export-in 1.6 GB: got '$v'"; fi
  else
    echo "SKIP e2e 4.37 low-memory row: no cgrun, no 4.37 export or no check/lowmem/pins-437.env"
  fi
else
  echo "SKIP e2e 4.37 project: release 4.37.0-rc1 not in config/components.json (tools/addrelease.py) or no check/sound/pins-437.env"
fi
env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" "$G11/proj/ok" "$G11/chal/ok" "$S/badpins" --preset sound --pins /etc/passwd \
  --threads 4 > "$S/badpins.log" 2>&1; rc=$?
if [ $rc = 2 ] && grep -q "must name a pins" "$S/badpins/result.json" 2>/dev/null; then ok "--pins outside check/sound/ refused (exit 2)"; else ko "--pins /etc/passwd: rc=$rc"; fi
# sound-auto + the conditional check: the frontier test's 'decomp' case (2 sorried helper lemmas) -> CONDITIONAL, exit 3
if "$PKG/check/frontier/check-frontier.sh" --preflight > /dev/null 2>&1; then
  env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" "$H/frontier/proj" "$H/frontier/chal" "$S/frontier" --preset sound-auto \
    --modulo-frontier auto --threads 8 --packages "$WS" > "$S/frontier.log" 2>&1; rc=$?
  v=$(python3 -I -c 'import json,sys; r=json.load(open(sys.argv[1])); f=r.get("frontier") or {}; print(r.get("verdict"), f.get("frontier_size"))' "$S/frontier/result.json" 2>/dev/null)
  if [ "$rc $v" = "3 CONDITIONAL 2" ]; then ok "e2e frontier (sound-auto + --modulo-frontier): exit 3 CONDITIONAL, 2 open lemmas"; else ko "e2e frontier: rc=$rc '$v'"; fi
else
  echo "SKIP frontier row: check/frontier/check-frontier.sh --preflight fails on this host"
fi
if [ -d "$WS/.lake/packages/mathlib/Mathlib" ] && [ "${SOUND_AUTO_SKIP_DUALMUT:-0}" != 1 ]; then
  mkdir -p "$S/src"; rsync -a --exclude=.lake --exclude=.git "$WS/.lake/packages/mathlib/" "$S/src/mathlib/"
  WS_MANIFEST="$WS/lake-manifest.json" ONLY=dualmut python3 -I "$G11/mkml.py" "$S/src/mathlib" "$S/gen" > /dev/null
  run dualmut "$S/gen/proj/dualmut" "$S/gen/chal/dualmut"
  row dualmut "ACCEPTED 0" B3
  n=$(grep -c '"event": "ktc-exempt"' "$S/dualmut/log/build-fast/sched.out" 2>/dev/null)
  if [ "${n:-0}" -ge 1 ]; then ok "dualmut: $n module(s) kept the build-time kernel check"; else ko "dualmut: no ktc-exempt event"; fi
fi
echo "RESULT pass=$pass fail=$fail"; [ $fail = 0 ]
