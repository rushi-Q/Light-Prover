#!/bin/bash
# tests/confirm-reject/run.sh [SCRATCH] : regression test of the false REJECT of a valid Mathlib-as-project
# slice and of the sound-mode option --confirm-reject. Runs on one host in ~10 min (16 threads). Cases, each through --preset sound without (plain)
# and with --confirm-reject (cr):
#   ok      honest core-only proof                       expect plain ACCEPTED,  cr ACCEPTED (no confirmation)
#   stmt    valid proof of a different statement         expect plain REJECTED,  cr REJECTED (B1 rebuilt, CS rejects again)
#   kfalse  'decide +kernel' on 2+2=5 (passes the skip-kernel-tc build, kernel-invalid)
#                                                        expect plain REJECTED,  cr REJECTED (the exact build B1 fails)
#   dualmut Mathlib-as-project slice (53 modules of Mathlib 0df444a built from source, generated by mkml.py) whose target
#           Decidable.lt_or_eq_of_le' is generated by @[to_dual]; with skip-kernel-tc the untrusted build keeps an ill-typed
#           first attempt -> plain REJECTED (= the documented false reject), cr ACCEPTED (export = official)
# Prints PASS/FAIL rows and RESULT; exit 0 iff all PASS. The plain dualmut row only documents the known false reject
# (PASS if it is REJECTED or ACCEPTED - a future preset without the defect may accept it).
set -u
H=$(cd "$(dirname "$(readlink -f "$0")")" && pwd); FV=$(cd "$H/../.." && pwd)/bin/fastverify
LL=$(cd "$H/../../.." && pwd); WS=${WS:-$LL/verify/challenge}
S=$(mktemp -d "${1:-${TMPDIR:-/tmp}}/v07cr.XXXXXX") || exit 2
trap 'chmod -R u+w "$S" 2>/dev/null; rm -rf "$S"' EXIT
pass=0; fail=0
row() { # case flag want...
  local c=$1 f=$2; shift 2
  local v; v=$(python3 -I -c 'import json,sys; r=json.load(open(sys.argv[1])); print(r.get("verdict"), r.get("exit"))' "$S/$c.$f/result.json" 2>/dev/null)
  local ok=0; for w in "$@"; do [ "$v" = "$w" ] && ok=1; done
  if [ $ok = 1 ]; then echo "PASS $c $f: $v"; pass=$((pass+1)); else echo "FAIL $c $f: got '$v' want one of: $*"; fail=$((fail+1)); fi
}
run() { # case proj chal flag
  env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 "$FV" "$2" "$3" "$S/$1.$4" --preset sound --threads 16 --packages "$WS" \
    $( [ "$4" = cr ] && echo --confirm-reject ) > "$S/$1.$4.log" 2>&1
}
for c in ok stmt kfalse; do for f in plain cr; do run $c "$H/proj/$c" "$H/chal/$c" $f; done; done
row ok plain "ACCEPTED 0"; row ok cr "ACCEPTED 0"; row stmt plain "REJECTED 1"; row stmt cr "REJECTED 1"
row kfalse plain "REJECTED 1"; row kfalse cr "REJECTED 1"
if [ -d "$WS/.lake/packages/mathlib/Mathlib" ]; then
  mkdir -p "$S/src"; rsync -a --exclude=.lake --exclude=.git "$WS/.lake/packages/mathlib/" "$S/src/mathlib/"
  WS_MANIFEST="$WS/lake-manifest.json" ONLY=dualmut python3 -I "$H/mkml.py" "$S/src/mathlib" "$S/gen" > /dev/null
  for f in plain cr; do run dualmut "$S/gen/proj/dualmut" "$S/gen/chal/dualmut" $f; done
  row dualmut plain "REJECTED 1" "ACCEPTED 0"; row dualmut cr "ACCEPTED 0"
fi
# the sound-mode orchestrator regression rows (export-in cases; must stay green with the option present)
while read -r st rest; do
  case $st in PASS) echo "PASS preset.sh $rest"; pass=$((pass+1));; FAIL) echo "FAIL preset.sh $rest"; fail=$((fail+1));; esac
done < <(CHECK_SOUND_TEST_DIR="$S" bash "$H/../../check/sound/test/preset.sh" 2>&1)
echo "RESULT pass=$pass fail=$fail"; [ $fail = 0 ]
